CREATE TABLE server_configs (
    id VARCHAR(36) PRIMARY KEY,
    guild_id VARCHAR(20) UNIQUE NOT NULL,
    reports_channel_id VARCHAR(20),
    active_role_name VARCHAR(100) NOT NULL DEFAULT 'Active of the Week',
    active_role_id VARCHAR(20),
    inactivity_threshold_days INT NOT NULL DEFAULT 30,
    weekly_schedule_cron VARCHAR(50) NOT NULL DEFAULT '0 0 * * 1',
    timezone VARCHAR(50) NOT NULL DEFAULT 'UTC',
    enabled_features JSON NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_guild_id (guild_id),
    INDEX idx_server_config_updated (updated_at DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE user_activity_records (
    id VARCHAR(36) PRIMARY KEY,
    guild_id VARCHAR(20) NOT NULL,
    user_id VARCHAR(20) NOT NULL,
    username VARCHAR(100) NOT NULL,
    avatar_url VARCHAR(500) NULL,
    discriminator VARCHAR(10),
    is_bot BOOLEAN NOT NULL DEFAULT FALSE,
    current_week_num INT NOT NULL DEFAULT 1,
    total_messages BIGINT NOT NULL DEFAULT 0,
    total_voice_minutes INT NOT NULL DEFAULT 0,
    current_week_voice_minutes INT NOT NULL DEFAULT 0,
    current_week_messages INT NOT NULL DEFAULT 0,
    previous_week_messages INT NOT NULL DEFAULT 0,
    last_message_at TIMESTAMP NULL,
    last_voice_join_at TIMESTAMP NULL,
    last_activity_at TIMESTAMP NULL,
    has_active_role BOOLEAN NOT NULL DEFAULT FALSE,
    active_role_granted_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL,
    UNIQUE INDEX idx_user_activity_guild_user (guild_id, user_id),
    INDEX idx_guild_last_activity (guild_id, last_activity_at),
    INDEX idx_guild_current_week (guild_id, current_week_messages DESC),
    INDEX idx_updated_at (updated_at),
    INDEX idx_has_active_role (guild_id, has_active_role),
    INDEX idx_user_activity_last_activity (guild_id, last_activity_at DESC),
    INDEX idx_user_activity_messages (guild_id, total_messages DESC),
    INDEX idx_user_activity_voice (guild_id, total_voice_minutes DESC),
    INDEX idx_user_activity_week (guild_id, current_week_num, current_week_messages DESC),
    INDEX idx_user_activity_inactive (guild_id, last_activity_at ASC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE weekly_activities (
    id VARCHAR(36) PRIMARY KEY,
    guild_id VARCHAR(20) NOT NULL,
    user_id VARCHAR(20) NOT NULL,
    username VARCHAR(100) NOT NULL,
    avatar_url VARCHAR(500) NULL,
    year INT NOT NULL,
    week_num INT NOT NULL,
    week_start TIMESTAMP NOT NULL,
    week_end TIMESTAMP NOT NULL,
    message_count INT NOT NULL DEFAULT 0,
    total_messages INT NOT NULL DEFAULT 0,
    voice_minutes INT NOT NULL DEFAULT 0,
    rank_position INT NOT NULL DEFAULT 0,
    received_role BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE INDEX idx_weekly_activity_guild_week (guild_id, year, week_num, user_id),
    INDEX idx_weekly_activities_messages (guild_id, year, week_num, total_messages DESC),
    INDEX idx_weekly_activities_voice (guild_id, year, week_num, voice_minutes DESC),
    INDEX idx_weekly_activities_rank (guild_id, year, week_num, rank_position ASC),
    INDEX idx_weekly_activities_role (received_role),
    INDEX idx_weekly_activities_top (guild_id, year, week_num, total_messages DESC, voice_minutes DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE message_exports (
    id VARCHAR(36) PRIMARY KEY,
    guild_id VARCHAR(20) NOT NULL,
    channel_id VARCHAR(20) NOT NULL,
    requester_user_id VARCHAR(20) NOT NULL,
    export_type ENUM('date_range', 'recent') NOT NULL,
    summary_status ENUM('pending', 'completed', 'failed', 'skipped') NOT NULL,
    start_time TIMESTAMP NULL,
    end_time TIMESTAMP NULL,
    message_count INT NOT NULL,
    summary_text TEXT NULL,
    summary_error TEXT NULL,
    gpt_tokens_used INT NULL,
    processing_duration_ms INT NULL,
    completed_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL,
    INDEX idx_guild_requester (guild_id, requester_user_id),
    INDEX idx_created_at (created_at),
    INDEX idx_summary_status (summary_status),
    INDEX idx_message_exports_status (summary_status),
    INDEX idx_message_exports_guild_created (guild_id, created_at DESC),
    INDEX idx_message_exports_user_created (requester_user_id, created_at DESC),
    INDEX idx_message_exports_archived (deleted_at),
    INDEX idx_exports_user_status_created (requester_user_id, summary_status, created_at DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE weekly_reports (
    id VARCHAR(36) PRIMARY KEY,
    guild_id VARCHAR(20) NOT NULL,
    year INT NOT NULL,
    week_num INT NOT NULL,
    week_start TIMESTAMP NOT NULL,
    week_end TIMESTAMP NOT NULL,
    total_users INT NOT NULL DEFAULT 0,
    active_users INT NOT NULL DEFAULT 0,
    total_messages BIGINT NOT NULL,
    report_content JSON NOT NULL,
    top_5_users JSON NOT NULL,
    channel_id VARCHAR(100) NULL,
    posted_channel_id VARCHAR(100) NULL,
    posted_message_id VARCHAR(100) NULL,
    posted_at TIMESTAMP NULL,
    generated_at TIMESTAMP NOT NULL,
    generated_by_user VARCHAR(100) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL,
    UNIQUE INDEX idx_weekly_reports_guild_week (guild_id, year, week_num),
    INDEX idx_weekly_reports_created (guild_id, created_at DESC),
    INDEX idx_weekly_reports_posted (posted_at DESC),
    INDEX idx_weekly_reports_channel (channel_id),
    INDEX idx_deleted_at (deleted_at),
    INDEX idx_weekly_reports_active (guild_id, year DESC, week_num DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
